export type BlockFormLocale = keyof typeof BLOCK_FORM_STRINGS

/**
 * Build the block-form translator (`bt`). Returns the Chinese rendering for an
 * English source string in the zh locale; en (or any untranslated string)
 * returns the source text unchanged.
 */
export function makeBlockTranslate(locale: 'en' | 'zh'): (english: string) => string {
  const dict = BLOCK_FORM_STRINGS.zh as Record<string, string>
  return (english: string) => {
    if (locale !== 'zh' || !english) return english
    return dict[english] ?? english
  }
}

/** Resolve an editor locale from the stored locale preference. */
export function resolveEditorLocale(stored: string | undefined): EditorLocale {
  if (stored === 'en') return 'en'
  if (stored === 'zh-CN') return 'zh'
  // auto: follow browser language.
  const nav = (typeof navigator !== 'undefined' ? navigator.language : '').toLowerCase()
  return nav.startsWith('zh') ? 'zh' : 'en'
}

export function makeTranslate(locale: EditorLocale): TranslateFn {
  const dict = EDITOR_STRINGS[locale]
  return (key) => dict[key] ?? EDITOR_STRINGS.en[key] ?? key
}
